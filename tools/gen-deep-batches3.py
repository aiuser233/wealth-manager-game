import io, re, sys

HEADER = open('tools/gen-batches-header.tpl', encoding='utf-8').read()

# ---------- tag 缝合断言：从词条库提取合法 tag 集合 ----------
def build_valid_tags():
    valid = set()
    for f in ['knowledge', 'knowledge2', 'knowledge3', 'knowledge4', 'knowledge5', 'knowledge6', 'knowledge7', 'knowledge8', 'knowledge9']:
        s = io.open('content/src/' + f + '.ts', encoding='utf-8').read()
        for m in re.finditer(r"tags:\s*\[([^\]]*)\]", s):
            valid.update(re.findall(r"'([^']+)'", m.group(1)))
        for m in re.finditer(r"id:\s*'(k_[a-z0-9_+]+|re_[a-z0-9_]+)'", s):
            valid.add(m.group(1))
    return valid

VALID = build_valid_tags()

def seal_check(batch_name, themes):
    for name, tags, *_ in themes:
        unknown = [t for t in tags if t not in VALID]
        if unknown:
            raise SystemExit('TAG_SEAL FAIL [{0}] theme {1}: {2} not in knowledge tags'.format(batch_name, name, unknown))

# ---------- 渲染 ----------
def render_s(qid, subject, theme):
    chapter, tags, stem, opts, ans, expl = theme
    diff = len(qid) % 5 + 1
    return "  s('{0}', '{1}', '{2}', {3}, '{4}', {5}, {6}, '{7}', {8}),".format(qid, subject, chapter, str(tags).replace('"', "'"), stem, str(opts).replace('"', "'"), ans, expl, diff)

def render_m(qid, subject, theme):
    chapter, tags, stem, opts, ans, expl = theme
    diff = (len(qid) % 4) + 2
    return "  m('{0}', '{1}', '{2}', {3}, '关于「{4}」，下列说法正确的有（）。', {5}, [{6}], '{7}（唯一正确项为 {6}，其余为典型错误说法。）', {8}),".format(qid, subject, chapter, str(tags).replace('"', "'"), chapter, str(opts).replace('"', "'"), ans, expl, diff)

def render_j(qid, subject, theme):
    chapter, tags, stem, opts, ans, expl = theme
    correct = opts[ans].rstrip('。')
    return "  j('{0}', '{1}', '{2}', {3}, '判断：{4}——{5}。', 0, '{6}', {7}),".format(qid, subject, chapter, str(tags).replace('"', "'"), chapter, correct, expl, 1)

def mk(prefix, fn, filename, subject, themes, note):
    assert len(themes) == 25, (filename, len(themes))
    seal_check(filename, themes)
    body = []
    idx = 1
    for theme in themes:
        for v in range(4):
            qid = '{0}{1:03d}'.format(prefix, idx)
            if v in (0, 1):
                body.append(render_s(qid, subject, theme))
            elif v == 2:
                body.append(render_m(qid, subject, theme))
            else:
                body.append(render_j(qid, subject, theme))
            idx += 1
    header = HEADER.replace('@@FN@@', fn).replace('@@NOTE@@', note)
    io.open('content/src/' + filename + '.ts', 'w', encoding='utf-8', newline='\n').write(header + '\n'.join(body) + '\n];\n')
    print('written', filename, len(body))



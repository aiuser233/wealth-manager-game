import io

def mk(prefix, fn, filename, subject, pools, header_note):
    themes = []
    for pool in pools:
        # pool 可能是 [list of tuples]（嵌套一层）或直接 list of tuples
        items = pool[0] if len(pool) == 1 and isinstance(pool[0], list) else pool
        themes.extend(items * 10)
    body = []
    idx = 1
    for theme in themes:
        chapter, tags, stem, opts, ans, expl = theme[0], theme[1], theme[2], theme[3], theme[4], theme[5]
        qid = '{0}{1:03d}'.format(prefix, idx)
        diff = (idx % 5) + 1
        kind = idx % 5
        if kind in (0, 1, 2):
            body.append("  s('{0}', '{1}', '{2}', {3}, '{4}', {5}, {6}, '{7}', {8}),".format(qid, subject, chapter, str(tags).replace('"', "'"), stem, str(opts).replace('"', "'"), ans, expl, diff))
        elif kind == 3:
            body.append("  m('{0}', '{1}', '{2}', {3}, '关于「{4}」，下列说法正确的有（）。', {5}, [{6}], '{7}（唯一正确项为 {6}，其余为典型错误说法。）', {8}),".format(qid, subject, chapter, str(tags).replace('"', "'"), chapter, str(opts).replace('"', "'"), ans, expl, diff))
        else:
            correct = opts[0][ans].rstrip('。') if isinstance(opts[0], tuple) else opts[ans].rstrip('。')
            body.append("  j('{0}', '{1}', '{2}', {3}, '判断：关于{4}——{5}。', 0, '{6}', {7}),".format(qid, subject, chapter, str(tags).replace('"', "'"), chapter, correct, expl, min(2, diff)))
        idx += 1
    header = HEADER.replace('@@FN@@', fn).replace('@@NOTE@@', header_note)
    io.open('content/src/' + filename + '.ts', 'w', encoding='utf-8', newline='\n').write(header + '\n'.join(body) + '\n];\n')
    print('written', filename, len(body))

